#!/bin/bash
# status_icons_2x3：参考 8 张状态标志生成 2 行 3 列 6 图标网格（Seedream 5.5 / image2image / 3:2 / 2K / transparent）
set -e
export PATH="$HOME/.libtv:$PATH"
cd /e/pixel_world

PROMPT='参考 {{Node "status_ref_8_flags"}} 中 8 个状态图标的统一风格：回合制战棋游戏状态图标，菱形徽章底（旋转45度的正方形），徽章带深色描边、表面为同色系渐变立体感，中央为白色粗剪影符号，符号简洁醒目、高对比，透明背景。生成一张 2 行 3 列（2 行 3 列，共 6 个图标）的状态图标素材表，每个图标为独立完整的菱形徽章，大小一致、间距均匀、互不重叠：第 1 行第 1 个——力量提升：橙金色菱形+白色粗壮向上箭头与握拳剪影，象征力量增强；第 1 行第 2 个——防御提升：蓝色菱形+白色盾牌剪影，象征防御增强；第 1 行第 3 个——速度提升：青绿色菱形+白色双重向右箭头与风纹剪影，象征速度增强；第 2 行第 1 个——防御削弱：灰色菱形+白色碎裂盾牌剪影（盾面带裂纹），象征防御削弱；第 2 行第 2 个——通用增益：绿色菱形+白色向上箭头与四角小星星剪影，象征任意属性获得增益；第 2 行第 3 个——通用减益：紫色菱形+白色向下箭头剪影，象征任意属性受到减益。6 个图标的徽章造型、描边粗细、白色剪影质感与参考图中 8 个图标的风格完全一致。不要边框、不要网格线、不要文字标注、不要底座、不要投影、不要任何底色。'

libtv node --x 2600 --y 100 create "status_icons_2x3" -t image \
  --left "status_ref_8_flags" \
  -s "model=Seedream 5.5" \
  -s modeType=image2image \
  -s ratio=3:2 \
  -s quality=2K \
  -s background=transparent \
  --prompt "$PROMPT" \
  --run
